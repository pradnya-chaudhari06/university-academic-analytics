-- ------------------------------------------------------------------------------
-- FactStudentRiskStatus
-- Periodic snapshot fact table capturing individual student risk standing,
-- cumulative performance, biometric attendance metrics, and flagged bottlenecks
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS fact_student_risk_status (
    risk_key                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_key             BIGINT NOT NULL REFERENCES dim_student(student_key) ON DELETE RESTRICT,
    department_key          INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    time_key                INTEGER NOT NULL REFERENCES dim_time(time_key) ON DELETE RESTRICT,
    current_gpa             NUMERIC(4, 2) NOT NULL CHECK (current_gpa BETWEEN 0.0 AND 10.0),
    attendance_percentage   NUMERIC(5, 2) NOT NULL CHECK (attendance_percentage BETWEEN 0.0 AND 100.0),
    failed_courses_count    INTEGER NOT NULL DEFAULT 0 CHECK (failed_courses_count >= 0),
    risk_level              VARCHAR(20) NOT NULL CHECK (risk_level IN ('High', 'Medium', 'Low', 'None')),
    is_at_risk              BOOLEAN NOT NULL,
    primary_risk_factor     VARCHAR(150),
    flagged_subject         VARCHAR(150),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_student_time_risk UNIQUE (student_key, time_key)
);

