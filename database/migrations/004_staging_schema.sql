DROP TABLE IF EXISTS _sync_outbox CASCADE;
DROP TABLE IF EXISTS etl_audit_log CASCADE;
DROP TABLE IF EXISTS stg_attendance CASCADE;
DROP TABLE IF EXISTS stg_exam_marks CASCADE;
DROP TABLE IF EXISTS stg_courses CASCADE;
DROP TABLE IF EXISTS stg_students CASCADE;

-- ------------------------------------------------------------------------------
-- 1. Staging Tables (Raw Operational Ingestion)
-- ------------------------------------------------------------------------------

-- Raw Student SIS Extract
CREATE TABLE stg_students (
    stg_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          VARCHAR(30) NOT NULL,
    student_name        VARCHAR(120) NOT NULL,
    gender              VARCHAR(15),
    date_of_birth       DATE,
    department_code     VARCHAR(20) NOT NULL,
    admission_year      INTEGER NOT NULL,
    academic_year       VARCHAR(20) NOT NULL,
    semester            VARCHAR(20) NOT NULL,
    section             VARCHAR(10) DEFAULT 'A',
    status              VARCHAR(20) DEFAULT 'Active',
    extracted_at        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Raw Curriculum Course Catalog Extract
CREATE TABLE stg_courses (
    stg_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code         VARCHAR(30) NOT NULL,
    course_name         VARCHAR(150) NOT NULL,
    department_code     VARCHAR(20) NOT NULL,
    credits             NUMERIC(3, 1) NOT NULL,
    semester            VARCHAR(20) NOT NULL,
    extracted_at        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Raw Exam Portal Marks Extract
CREATE TABLE stg_exam_marks (
    stg_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          VARCHAR(30) NOT NULL,
    course_code         VARCHAR(30) NOT NULL,
    marks               NUMERIC(5, 2) NOT NULL,
    semester            VARCHAR(20) NOT NULL,
    academic_year       VARCHAR(20) NOT NULL,
    evaluation_date     DATE NOT NULL,
    extracted_at        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Raw Biometric & LMS Attendance Extract
CREATE TABLE stg_attendance (
    stg_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          VARCHAR(30) NOT NULL,
    course_code         VARCHAR(30) NOT NULL,
    classes_conducted   INTEGER NOT NULL,
    classes_attended    INTEGER NOT NULL,
    semester            VARCHAR(20) NOT NULL,
    academic_year       VARCHAR(20) NOT NULL,
    log_date            DATE NOT NULL,
    extracted_at        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------------------------
-- 2. ETL Audit Log Table
-- Tracks operational batch extraction, transformation durations, and loaded records
-- ------------------------------------------------------------------------------
CREATE TABLE etl_audit_log (
    log_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id              VARCHAR(50) NOT NULL,
    job_name            VARCHAR(100) NOT NULL,
    source_system       VARCHAR(100) NOT NULL,
    target_table        VARCHAR(100) NOT NULL,
    status              VARCHAR(30) NOT NULL CHECK (status IN ('Started', 'Completed', 'Failed', 'In Progress')),
    records_extracted   INTEGER NOT NULL DEFAULT 0,
    records_loaded      INTEGER NOT NULL DEFAULT 0,
    records_rejected    INTEGER NOT NULL DEFAULT 0,
    duration_seconds    NUMERIC(6, 2) NOT NULL DEFAULT 0,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at        TIMESTAMPTZ,
    error_message       TEXT
);

COMMENT ON TABLE etl_audit_log IS 'Audit trail tracking automated ETL pipeline executions, record counts, and run durations';

-- ------------------------------------------------------------------------------
-- 3. Offline Write Outbox & Sync Queue
-- Captures mutations during SQLite offline fallback for deterministic replay
-- ------------------------------------------------------------------------------
CREATE TABLE _sync_outbox (
    outbox_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name          VARCHAR(100) NOT NULL,
    operation           VARCHAR(20) NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    record_key          VARCHAR(100) NOT NULL,
    payload_json        JSONB NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    synced_at           TIMESTAMPTZ,
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SYNCED', 'CONFLICT'))
);

CREATE INDEX idx_sync_outbox_status ON _sync_outbox(status);
CREATE INDEX idx_sync_outbox_table  ON _sync_outbox(table_name, record_key);

COMMENT ON TABLE _sync_outbox IS 'Queue table storing offline mutations for bi-directional synchronization with SQLite fallback';
