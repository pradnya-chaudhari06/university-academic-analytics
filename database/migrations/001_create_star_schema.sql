-- ==============================================================================
-- 1. DIMENSION TABLES
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1.1 DimDepartment
-- Captures academic faculty and department structural hierarchy
-- ------------------------------------------------------------------------------
CREATE TABLE dim_department (
    department_key      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code     VARCHAR(20) NOT NULL UNIQUE,
    department_name     VARCHAR(100) NOT NULL,
    faculty_name        VARCHAR(100) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE dim_department IS 'Dimension table storing academic department hierarchy';
COMMENT ON COLUMN dim_department.department_key IS 'Surrogate integer primary key';
COMMENT ON COLUMN dim_department.department_code IS 'Natural department code (e.g., CE, IT, EXTC, MECH, CIVIL)';

-- ------------------------------------------------------------------------------
-- 1.2 DimCourse
-- Academic course catalog and curriculum attributes
-- ------------------------------------------------------------------------------
CREATE TABLE dim_course (
    course_key          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code         VARCHAR(30) NOT NULL UNIQUE,
    course_name         VARCHAR(150) NOT NULL,
    department_key      INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    credits             NUMERIC(3, 1) NOT NULL CHECK (credits > 0),
    semester            VARCHAR(20) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE dim_course IS 'Dimension table storing academic courses and curriculum metadata';
COMMENT ON COLUMN dim_course.course_key IS 'Surrogate integer primary key';
COMMENT ON COLUMN dim_course.course_code IS 'Natural curriculum code (e.g., CS601, IT602)';

-- ------------------------------------------------------------------------------
-- 1.3 DimStudent
-- Student demographic and cohort enrollment dimension
-- ------------------------------------------------------------------------------
CREATE TABLE dim_student (
    student_key         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          VARCHAR(30) NOT NULL UNIQUE,
    student_name        VARCHAR(120) NOT NULL,
    gender              VARCHAR(15) CHECK (gender IN ('Male', 'Female', 'Non-Binary', 'Other')),
    date_of_birth       DATE,
    department_key      INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    admission_year      INTEGER NOT NULL CHECK (admission_year >= 2000 AND admission_year <= 2100),
    academic_year       VARCHAR(20) NOT NULL,
    semester            VARCHAR(20) NOT NULL,
    section             VARCHAR(10) NOT NULL DEFAULT 'A',
    status              VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Graduated', 'Suspended', 'Withdrawn', 'On Leave')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE dim_student IS 'Dimension table storing student profile, demographics, and cohort status';
COMMENT ON COLUMN dim_student.student_key IS 'Surrogate bigint primary key';
COMMENT ON COLUMN dim_student.student_id IS 'Natural university student identifier (e.g., STU1024)';

-- ------------------------------------------------------------------------------
-- 1.4 DimTime
-- Temporal dimension for granular academic calendar and longitudinal trend slicing
-- ------------------------------------------------------------------------------
CREATE TABLE dim_time (
    time_key            INTEGER PRIMARY KEY, -- Formatted as YYYYMMDD (e.g., 20260630) or surrogate integer
    date                DATE NOT NULL UNIQUE,
    day                 INTEGER NOT NULL CHECK (day BETWEEN 1 AND 31),
    month               INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name          VARCHAR(20) NOT NULL,
    quarter             INTEGER NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    semester            VARCHAR(20) NOT NULL,
    academic_year       VARCHAR(20) NOT NULL,
    year                INTEGER NOT NULL CHECK (year >= 2000),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE dim_time IS 'Temporal dimension for academic calendar analytics';
COMMENT ON COLUMN dim_time.time_key IS 'Surrogate time key in integer format (YYYYMMDD)';

-- ------------------------------------------------------------------------------
-- 1.5 DimGradeBand
-- Grade scale, grade points, marks range, and performance band classification
-- ------------------------------------------------------------------------------
CREATE TABLE dim_grade_band (
    grade_band_key      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade               VARCHAR(10) NOT NULL UNIQUE,
    grade_point         NUMERIC(4, 2) NOT NULL CHECK (grade_point BETWEEN 0.0 AND 10.0),
    grade_category      VARCHAR(50) NOT NULL CHECK (grade_category IN ('Excellent', 'Good', 'Average', 'Needs Support')),
    min_marks           NUMERIC(5, 2) NOT NULL CHECK (min_marks >= 0.0),
    max_marks           NUMERIC(5, 2) NOT NULL CHECK (max_marks <= 100.0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_marks_range CHECK (min_marks <= max_marks)
);

COMMENT ON TABLE dim_grade_band IS 'Dimension table for institutional grading criteria and classification tiers';
COMMENT ON COLUMN dim_grade_band.grade_band_key IS 'Surrogate integer primary key';

-- ==============================================================================
-- 2. FACT TABLES
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 2.1 FactAcademicPerformance
-- Granular exam and evaluation records across student, course, time, and department
-- ------------------------------------------------------------------------------
CREATE TABLE fact_academic_performance (
    performance_key     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_key         BIGINT NOT NULL REFERENCES dim_student(student_key) ON DELETE RESTRICT,
    course_key          INTEGER NOT NULL REFERENCES dim_course(course_key) ON DELETE RESTRICT,
    department_key      INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    time_key            INTEGER NOT NULL REFERENCES dim_time(time_key) ON DELETE RESTRICT,
    grade_band_key      INTEGER NOT NULL REFERENCES dim_grade_band(grade_band_key) ON DELETE RESTRICT,
    marks               NUMERIC(5, 2) NOT NULL CHECK (marks BETWEEN 0.0 AND 100.0),
    grade_point         NUMERIC(4, 2) NOT NULL CHECK (grade_point BETWEEN 0.0 AND 10.0),
    credits             NUMERIC(3, 1) NOT NULL CHECK (credits > 0),
    result_status       VARCHAR(20) NOT NULL CHECK (result_status IN ('Pass', 'Fail', 'Backlog', 'Absent', 'Exempted')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_student_course_time UNIQUE (student_key, course_key, time_key)
);

COMMENT ON TABLE fact_academic_performance IS 'Core academic fact table storing granular grades, marks, and credit evaluations';
COMMENT ON COLUMN fact_academic_performance.performance_key IS 'Surrogate bigint primary key';

-- ------------------------------------------------------------------------------
-- 2.2 FactAttendance
-- Granular lecture, lab, and tutorial attendance records
-- ------------------------------------------------------------------------------
CREATE TABLE fact_attendance (
    attendance_key        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_key           BIGINT NOT NULL REFERENCES dim_student(student_key) ON DELETE RESTRICT,
    course_key            INTEGER NOT NULL REFERENCES dim_course(course_key) ON DELETE RESTRICT,
    department_key        INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    time_key              INTEGER NOT NULL REFERENCES dim_time(time_key) ON DELETE RESTRICT,
    classes_conducted     INTEGER NOT NULL CHECK (classes_conducted > 0),
    classes_attended      INTEGER NOT NULL CHECK (classes_attended >= 0),
    attendance_percentage NUMERIC(5, 2) NOT NULL CHECK (attendance_percentage BETWEEN 0.0 AND 100.0),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_attendance_counts CHECK (classes_attended <= classes_conducted),
    CONSTRAINT uq_student_course_attendance UNIQUE (student_key, course_key, time_key)
);

COMMENT ON TABLE fact_attendance IS 'Attendance fact table tracking session conduct, presence, and calculated percentages';
COMMENT ON COLUMN fact_attendance.attendance_key IS 'Surrogate bigint primary key';

-- ------------------------------------------------------------------------------
-- 2.3 FactStudentRiskStatus
-- Periodic snapshot fact table capturing individual student risk standing,
-- cumulative performance, biometric attendance metrics, and flagged bottlenecks
-- ------------------------------------------------------------------------------
CREATE TABLE fact_student_risk_status (
    risk_key                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_key             BIGINT NOT NULL REFERENCES dim_student(student_key) ON DELETE RESTRICT,
    department_key          INTEGER NOT NULL REFERENCES dim_department(department_key) ON DELETE RESTRICT,
    time_key                INTEGER NOT NULL REFERENCES dim_time(time_key) ON DELETE RESTRICT,
    current_gpa             NUMERIC(4, 2) NOT NULL CHECK (current_gpa BETWEEN 0.0 AND 10.0),
    attendance_percentage   NUMERIC(5, 2) NOT NULL CHECK (attendance_percentage BETWEEN 0.0 AND 100.0),
    failed_courses_count    INTEGER NOT NULL DEFAULT 0 CHECK (failed_courses_count >= 0),
    risk_level              VARCHAR(20) NOT NULL CHECK (risk_level IN ('High', 'Medium', 'Low', 'None')),
    is_at_risk              BOOLEAN NOT NULL,
    primary_risk_factor     VARCHAR(150),
    flagged_subject         VARCHAR(150),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_student_time_risk UNIQUE (student_key, time_key)
);

COMMENT ON TABLE fact_student_risk_status IS 'Periodic snapshot fact table tracking cumulative academic standing, risk classification, and bottleneck subjects';
COMMENT ON COLUMN fact_student_risk_status.risk_key IS 'Surrogate bigint primary key';

